// The playtest tools, shared by the MCP server (mcp.js) and the command line (pt.js)
const D = require('./driver.js');

module.exports = [
  { name: 'pt_start', description: 'Start the game in headless Chrome at phone size (375x812) on paused virtual time, its own port and profile. fresh: true empties the profile (no characters). Returns the screen as text.',
    schema: { type: 'object', properties: { fresh: { type: 'boolean' } } },
    run: (a) => D.start({ fresh: !!a.fresh }) },
  { name: 'pt_look', description: 'The screen as a player sees it, as text: the player line (level, xp, hp, resource, money, place), controls a finger can reach with ids [e1].., readable text in reading order. Covered and off-screen controls are counted, not listed.',
    schema: { type: 'object', properties: { all: { type: 'boolean', description: 'include text covered by the top layer' } } },
    run: (a) => D.look({ all: !!a.all }) },
  { name: 'pt_tap', description: 'Tap a control like a finger: by id from the last look (e12) or a label regex. Runs the clock 0.4 s (or wait seconds) and returns the new screen; says so when the tap changed nothing.',
    schema: { type: 'object', properties: { target: { type: 'string' }, wait: { type: 'number' } }, required: ['target'] },
    run: (a) => D.tap(a.target, { wait: a.wait }) },
  { name: 'pt_advance', description: 'Run the game clock forward. Stops early on a level-up, death, the fight ending or starting, arriving, or a new dialog/cutscene (until: "any", the default), or only on level/death/fight end (until: "time"), or never (until: "none").',
    schema: { type: 'object', properties: { seconds: { type: 'number' }, until: { type: 'string', enum: ['any', 'time', 'none'] } }, required: ['seconds'] },
    run: (a) => D.advance(a.seconds, { until: a.until }) },
  { name: 'pt_scroll', description: 'Scroll the scrollable area under the middle of the screen (or the one holding target) up or down, then look.',
    schema: { type: 'object', properties: { dir: { type: 'string', enum: ['up', 'down'] }, target: { type: 'string' } } },
    run: (a) => D.scroll(a.dir || 'down', a.target) },
  { name: 'pt_check', description: 'Check the screen now for bugs and rough edges: page errors, NaN/undefined/[object] in text, sideways scroll, off-screen or clipped text, tap targets under 32x28, player numbers out of range, spoilers (G.nameable).',
    schema: { type: 'object', properties: {} },
    run: () => D.check() },
  { name: 'pt_shot', description: 'A screenshot, only when the look itself is under test. scale 0.2-1 (default 0.5). Saved to file when given.',
    schema: { type: 'object', properties: { scale: { type: 'number' }, file: { type: 'string' } } },
    run: (a) => D.shot(a.scale || 0.5, a.file), image: true },
  { name: 'pt_eval', description: 'Run JS in the page to read or stage game state (G, D, E, B, SOC). An expression, or a body with return. For setup and diagnosis, never to play.',
    schema: { type: 'object', properties: { js: { type: 'string' } }, required: ['js'] },
    run: (a) => D.evaluate(a.js) },
  { name: 'pt_journal', description: 'Every step taken this session, with times.',
    schema: { type: 'object', properties: {} },
    run: () => D.journal() },
  { name: 'pt_stop', description: 'Close the browser and the server (the profile and its characters stay).',
    schema: { type: 'object', properties: {} },
    run: () => D.stop() },
];

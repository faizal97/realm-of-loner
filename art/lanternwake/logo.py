# The Lanternwake logo: the game's plate, one candle lit for the dead as the keystone, LANTERNWAKE in candle wax with
# wax running from the tops. Writes art/lanternwake/logo.svg and src/art_lanternwake_logo.js (ART.lanternwakeLogo).
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'brand'))
from lockup import word, centred, letters, GOLD, metal, plate, write, CAP
H = os.path.dirname(os.path.abspath(__file__))
W, Hh, INK = 640, 300, '#0a0b18'
base = 230; big, bw = centred('LANTERNWAKE', 76, base, 0.03, W); bx = (W - bw) / 2
sub, sw = centred('THE AUTUMN FESTIVAL', 18, 282, 0.24, W); sx = (W - sw) / 2
top = base - 76 * CAP
drips = ''.join(f'<path d="M{x - 3.2},{top + 1} L{x + 3.2},{top + 1} L{x + 2.4},{top + 6 + n} Q{x},{top + 10 + n} {x - 2.4},{top + 6 + n} Z" fill="#fff6dc" stroke="{INK}" stroke-width="1.4"/>'
                for x, n in [(bx + 22, 4), (bx + 118, 7), (bx + 214, 2), (bx + 300, 6), (bx + 392, 3), (bx + 486, 8), (bx + 560, 4)])
leaves = ''.join(f'<path d="M0,-7 Q6,-2 0,7 Q-6,-2 0,-7 Z M0,-6 L0,6" transform="translate({x},{y}) rotate({r}) scale(1.9)" fill="{c}" stroke="{INK}" stroke-width="1.6"/>'
                 for x, y, r, c in [(236, 112, -30, '#c8542a'), (404, 96, 40, '#d98a2a'), (88, 150, 20, '#a8401e'), (566, 164, -50, '#c8542a'),
                                    (190, 290, 70, '#d98a2a'), (452, 288, -20, '#a8401e'), (30, 70, 10, '#d98a2a'), (612, 70, -15, '#a8401e')])
candle = f'''<g transform="translate({W / 2},0)">
    <ellipse cx="0" cy="96" rx="46" ry="46" fill="#ffb24a" opacity=".38" filter="url(#lkBlur)"/>
    <path d="M-16,112 L-16,150 L16,150 L16,112 Q8,108 0,111 Q-8,108 -16,112 Z" fill="url(#lkWax)" stroke="{INK}" stroke-width="3.4" stroke-linejoin="round"/>
    <path d="M6,111 L6,124 Q8,128 10,124 L10,112" fill="#fff6dc" stroke="{INK}" stroke-width="1.4"/>
    <path d="M0,110 L0,102" stroke="{INK}" stroke-width="2.4" stroke-linecap="round"/>
    <path d="M0,74 C7,84 9,92 0,102 C-9,92 -7,84 0,74 Z" fill="#ff9a2e" stroke="#c85a10" stroke-width="1.4"/>
    <path d="M0,84 C3,89 4,94 0,99 C-4,94 -3,89 0,84 Z" fill="#fff0b0"/>
    <path d="M-40,150 L40,150 Q36,160 0,160 Q-36,160 -40,150 Z" fill="url(#lkGold)" stroke="{INK}" stroke-width="3.4" stroke-linejoin="round"/>
  </g>'''
rule = lambda a, b: f'<path d="M{a},276 L{b},276" stroke="{INK}" stroke-width="5"/><path d="M{a},276 L{b},276" stroke="#f0c45a" stroke-width="2"/>'
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{Hh}" viewBox="0 0 {W} {Hh}">
  <!-- The Lanternwake logo. Generated by art/lanternwake/logo.py -->
  <defs>{GOLD.format(id="lkGold")}{metal("lkCandle", ("#fffaf0", "#ffe2a6", "#9a5a1c", "#f0b85a", "#7a3e12"))}
    <linearGradient id="lkWax" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#e8d6b0"/><stop offset=".5" stop-color="#fff6dc"/><stop offset="1" stop-color="#cdb88e"/></linearGradient>
    <filter id="lkBlur" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="10"/></filter>
  </defs>
  <ellipse cx="320" cy="200" rx="260" ry="40" fill="#ffb24a" opacity=".12" filter="url(#lkBlur)"/>
  {leaves}{plate(W, "lkGold", "#1a1f3a", INK)}
  {candle}
  {letters(big, 8, "url(#lkCandle)", INK)}
  {rule(sx - 120, sx - 18)}{rule(sx + sw + 18, sx + sw + 120)}
  {letters(sub, 4, "url(#lkCandle)", INK)}
</svg>
'''
print('logo.svg', write(svg, os.path.join(H, 'logo.svg'), 'art_lanternwake_logo.js', 'lanternwakeLogo', 'art/lanternwake/logo.py'))

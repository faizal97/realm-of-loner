# The Longnight logo: the game's plate, a shut door with the hearth's light under it as the keystone, LONGNIGHT in frost
# with snow on every letter. Writes art/longnight/logo.svg and src/art_longnight_logo.js (ART.longnightLogo), shown on
# the title screens while the festival is on. Needs fontTools + brotli (the face comes from fonts/fonts.local.css).
import base64, json, os, re, sys
H = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(H, '..', '..')
sys.path.insert(0, os.path.join(H, '..', 'brand')); from lockup import word, centred  # the game's face as outlines (art/brand/lockup.py)

W, Hh = 640, 300
r1, r1w = word('REALM', 40, 0, 0, 0.08); of_, ofw = word('OF', 22, 0, 0, 0.06); r2, r2w = word('LONER', 40, 0, 0, 0.08)
gap = 10; tot = r1w + gap + ofw + gap + r2w; nx = (W - tot) / 2; px0, px1 = nx - 34, nx + tot + 34
r1, _ = word('REALM', 40, nx, 56, 0.08); of_, _ = word('OF', 22, nx + r1w + gap, 56, 0.06); r2, _ = word('LONER', 40, nx + r1w + gap + ofw + gap, 56, 0.08)
big, _ = centred('LONGNIGHT', 90, 232, 0.03, W)
sub, sw = centred('THE WINTER FESTIVAL', 18, 282, 0.24, W); sx = (W - sw) / 2
CAP = 232 - 90 * 0.70  # Marcellus caps stand about 0.7 em: the snow lies on the top few pixels
def letters(d, sw_, fill):
    return (f'<path d="{d}" fill="#06101e" stroke="#06101e" stroke-width="{sw_}" stroke-linejoin="round" transform="translate(0,4)"/>'
            f'<path d="{d}" fill="none" stroke="#06101e" stroke-width="{sw_}" stroke-linejoin="round"/><path d="{d}" fill="{fill}"/>'
            f'<path d="{d}" fill="none" stroke="#ffffff" stroke-width="1" opacity=".5" transform="translate(0,-1)"/>')
flakes = ''.join(f'<circle cx="{x}" cy="{y}" r="{r}" fill="#ffffff" opacity="{o}"/>' for x, y, r, o in [
    (60, 110, 2, .8), (110, 40, 1.4, .6), (560, 50, 1.6, .7), (600, 130, 2.2, .8), (36, 210, 1.5, .6), (590, 230, 1.4, .6),
    (150, 150, 1.2, .5), (500, 140, 1.3, .5), (210, 290, 1.6, .6), (440, 292, 1.4, .5), (330, 12, 1.2, .5), (20, 60, 1.1, .5)])
door = f'''<g transform="translate({W / 2},0)">
    <ellipse cx="0" cy="150" rx="64" ry="16" fill="#ffb24a" opacity=".55" filter="url(#lnBlur)"/>
    <path d="M-34,148 L-34,96 Q-34,70 0,70 Q34,70 34,96 L34,148 Z" fill="#140c06" stroke="#06101e" stroke-width="6" stroke-linejoin="round"/>
    <path d="M-28,146 L-28,98 Q-28,77 0,77 Q28,77 28,98 L28,146 Z" fill="url(#lnWood)"/>
    <path d="M-9.5,77 L-9.5,146 M9.5,77 L9.5,146" stroke="#3a220f" stroke-width="2"/>
    <path d="M-28,100 L28,100 M-28,130 L28,130" stroke="#20242c" stroke-width="5"/><path d="M-28,100 L28,100 M-28,130 L28,130" stroke="#6d7684" stroke-width="2"/>
    <circle cx="16" cy="116" r="3.4" fill="#20242c"/><path d="M14.6,118 L13.6,124 L18.4,124 L17.4,118 Z" fill="#ffcf7a"/>
    <rect x="-30" y="144" width="60" height="5" fill="#ffd27a" filter="url(#lnSoft)"/>
    <path d="M-36,96 Q-36,66 0,66 Q36,66 36,96 Q30,90 24,94 Q18,86 10,90 Q4,84 -4,89 Q-12,84 -18,92 Q-26,88 -36,96 Z" fill="#f4f9ff" stroke="#06101e" stroke-width="2.4" stroke-linejoin="round"/>
    <path d="M-38,148 L38,148 L44,156 L-44,156 Z" fill="#2a3a56" stroke="#06101e" stroke-width="3" stroke-linejoin="round"/>
  </g>'''
plate = (f'<path d="M{px0},16 L{px1},16 L{px1 + 16},44 L{px1},72 L{px0},72 L{px0 - 16},44 Z" fill="#14203a" stroke="#06101e" stroke-width="6" stroke-linejoin="round"/>'
         f'<path d="M{px0},16 L{px1},16 L{px1 + 16},44 L{px1},72 L{px0},72 L{px0 - 16},44 Z" fill="none" stroke="#d9a744" stroke-width="2.4" stroke-linejoin="round"/>')
rule = lambda x1, x2: f'<path d="M{x1},276 L{x2},276" stroke="#06101e" stroke-width="5"/><path d="M{x1},276 L{x2},276" stroke="#cfe6ff" stroke-width="2"/>'
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{Hh}" viewBox="0 0 {W} {Hh}">
  <!-- The Longnight logo. Generated by art/longnight/logo.py -->
  <defs>
    <linearGradient id="lnGold" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fff1b8"/><stop offset=".42" stop-color="#f0c45a"/><stop offset=".5" stop-color="#9a6420"/><stop offset=".62" stop-color="#d9a744"/><stop offset="1" stop-color="#7a4c16"/></linearGradient>
    <linearGradient id="lnFrost" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#ffffff"/><stop offset=".42" stop-color="#cfe6ff"/><stop offset=".5" stop-color="#3a5a86"/><stop offset=".64" stop-color="#9fc4ee"/><stop offset="1" stop-color="#2a4466"/></linearGradient>
    <linearGradient id="lnWood" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#4a2c14"/><stop offset=".5" stop-color="#6e4420"/><stop offset="1" stop-color="#3e2410"/></linearGradient>
    <filter id="lnBlur" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="8"/></filter>
    <filter id="lnSoft" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="1.6"/></filter>
    <clipPath id="lnCap"><rect x="0" y="{CAP - 4}" width="{W}" height="9"/></clipPath>
  </defs>
  {flakes}{plate}{letters(r1, 5, 'url(#lnGold)')}{letters(of_, 4, 'url(#lnGold)')}{letters(r2, 5, 'url(#lnGold)')}
  {door}
  {letters(big, 9, 'url(#lnFrost)')}
  <g clip-path="url(#lnCap)"><path d="{big}" fill="#ffffff" stroke="#ffffff" stroke-width="5" stroke-linejoin="round"/></g>
  {rule(sx - 120, sx - 18)}{rule(sx + sw + 18, sx + sw + 120)}
  {letters(sub, 4, 'url(#lnFrost)')}
</svg>
'''
open(os.path.join(H, 'logo.svg'), 'w').write(svg)
flat = re.sub(r'<!--.*?-->', '', svg, flags=re.S); flat = re.sub(r'>\s+<', '><', flat).strip()
open(os.path.join(ROOT, 'src', 'art_longnight_logo.js'), 'w').write('// The Longnight logo, generated by art/longnight/logo.py; do not edit by hand.\n(function (root) { root.ART = root.ART || {}; root.ART.longnightLogo = ' + json.dumps(flat) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
print('logo.svg', len(flat))

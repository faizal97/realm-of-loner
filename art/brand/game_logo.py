# The game's own logo: the app icon's lantern in its ring (you) before a skyline of dim windows (everyone else), and
# REALM of LONER carved under it. For the title screen when no saga or festival is on, the store pages and the README.
# Writes art/brand/game_logo.svg, art/brand/game_logo.png and src/art_game_logo.js (ART.gameLogo).
import os, re, subprocess
from lockup import word, centred, letters, GOLD, write
H = os.path.dirname(os.path.abspath(__file__))
icon = open(os.path.join(H, '..', 'logo', 'icon.svg')).read()
# the lantern, as drawn in the icon (its own gradients renamed so the page has no clashes)
lan = re.search(r'<g transform="translate\(96,102\) scale\(1.5\)" stroke-linejoin="round">(.*?)</g>\s*<!-- the gold tile border -->', icon, re.S).group(1)
for a in ('gold', 'glass', 'metal'): lan = lan.replace(f'url(#{a})', f'url(#gl{a.title()})')
defs = ''.join(re.search(rf'<linearGradient id="{a}".*?</linearGradient>', icon, re.S).group(0).replace(f'id="{a}"', f'id="gl{a.title()}"') for a in ('gold', 'glass', 'metal'))
W, Hh, INK = 640, 320, '#140f09'
r1, r1w = word('REALM', 70, 0, 0, 0.05); of_, ofw = word('OF', 36, 0, 0, 0.05); r2, r2w = word('LONER', 70, 0, 0, 0.05)
gap = 16; tot = r1w + gap + ofw + gap + r2w; nx = (W - tot) / 2; base = 250
r1, _ = word('REALM', 70, nx, base, 0.05); of_, _ = word('OF', 36, nx + r1w + gap, base, 0.05); r2, _ = word('LONER', 70, nx + r1w + gap + ofw + gap, base, 0.05)
tag, tw = centred('A WORLD OF YOUR OWN', 17, 300, 0.26, W); tx = (W - tw) / 2
cx, cy = W / 2, 100
town = ('M40,206 L40,170 L58,170 L58,150 L70,136 L82,150 L82,166 L104,166 L104,178 L118,178 L118,152 L130,138 L142,152 L142,186 '
        'L498,186 L498,152 L510,138 L522,152 L522,178 L536,178 L536,166 L558,166 L558,150 L570,136 L582,150 L582,170 L600,170 L600,206 Z')
wins = ''.join(f'<rect x="{x}" y="{y}" width="6" height="8" fill="#6e5a36"/>' for x, y in
               [(48, 182), (67, 154), (67, 174), (90, 176), (124, 160), (124, 176), (507, 160), (507, 176), (544, 176), (567, 154), (567, 174), (586, 182)])
rule = lambda a, b: f'<path d="M{a},292 L{b},292" stroke="{INK}" stroke-width="5"/><path d="M{a},292 L{b},292" stroke="#d9a744" stroke-width="2"/>'
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{Hh}" viewBox="0 0 {W} {Hh}">
  <!-- Realm of Loner, the game's logo. Generated by art/brand/game_logo.py -->
  <defs>{GOLD.format(id="glWord")}{defs}
    <radialGradient id="glGlow" cx="50%" cy="50%" r="50%"><stop offset="0" stop-color="#ffe9ae" stop-opacity=".9"/><stop offset=".35" stop-color="#ffc85a" stop-opacity=".45"/><stop offset="1" stop-color="#ff9d2a" stop-opacity="0"/></radialGradient>
  </defs>
  <path d="{town}" fill="#2c2217" stroke="{INK}" stroke-width="3" stroke-linejoin="round"/>{wins}
  <circle cx="{cx}" cy="{cy + 6}" r="96" fill="url(#glGlow)"/>
  <circle cx="{cx}" cy="{cy}" r="74" fill="#1a140d" stroke="{INK}" stroke-width="12"/>
  <circle cx="{cx}" cy="{cy}" r="74" fill="none" stroke="url(#glGold)" stroke-width="6.5"/>
  <circle cx="{cx}" cy="{cy}" r="68" fill="none" stroke="#6a4c22" stroke-width="1.4"/>
  <circle cx="{cx}" cy="{cy + 8}" r="60" fill="url(#glGlow)"/>
  <g transform="translate({cx},{cy + 10}) scale(1.85)" stroke-linejoin="round">{lan}</g>
  {letters(r1, 9, "url(#glWord)", INK)}{letters(of_, 6, "url(#glWord)", INK)}{letters(r2, 9, "url(#glWord)", INK)}
  {rule(tx - 110, tx - 16)}{rule(tx + tw + 16, tx + tw + 110)}
  {letters(tag, 4, "url(#glWord)", INK)}
</svg>
'''
print('game_logo.svg', write(svg, os.path.join(H, 'game_logo.svg'), 'art_game_logo.js', 'gameLogo', 'art/brand/game_logo.py'))
subprocess.run(['/opt/homebrew/bin/rsvg-convert', '-w', '1280', '-o', os.path.join(H, 'game_logo.png'), os.path.join(H, 'game_logo.svg')], check=True)

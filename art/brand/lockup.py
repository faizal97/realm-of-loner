# Shared parts for the game's logos (art/ruinfall, art/longnight, art/lanternwake …): the Marcellus SC face as outlines
# (the game's own display font, read from fonts/fonts.local.css), carved letters, and the "Realm of Loner" plate.
import base64, json, os, re
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
_css = open(os.path.join(ROOT, 'fonts', 'fonts.local.css')).read()
_b = next(x for x in re.findall(r'@font-face\{[^}]*\}', _css) if 'Marcellus' in x)
_tmp = os.path.join(os.path.dirname(__file__), '.marcellus.woff2')
open(_tmp, 'wb').write(base64.b64decode(re.search(r'base64,([A-Za-z0-9+/=]+)', _b).group(1)))
_F = TTFont(_tmp); os.remove(_tmp)
_cm, _gs, _hm, _upm = _F.getBestCmap(), _F.getGlyphSet(), _F['hmtx'], _F['head'].unitsPerEm
CAP = 0.70  # cap height in em

def word(text, size, x0, base, track=0.0):
    """outline path for text (size px, left edge x0, baseline base) and its width"""
    pen = SVGPathPen(_gs); k = size / _upm; x = 0.0
    for ch in text:
        if ch == ' ': x += size * 0.32; continue
        g = _cm[ord(ch)]; _gs[g].draw(TransformPen(pen, (k, 0, 0, -k, x0 + x, base))); x += _hm[g][0] * k + track * size
    return re.sub(r'(\d+\.\d)\d+', r'\1', pen.getCommands()), x - track * size

def centred(text, size, base, track, W):
    _, w = word(text, size, 0, 0, track); d, _ = word(text, size, (W - w) / 2, base, track); return d, w

def letters(d, sw, fill, ink='#140f09'):
    """carved letters: a drop shadow, a dark outline, the fill, a thin top light"""
    return (f'<path d="{d}" fill="{ink}" stroke="{ink}" stroke-width="{sw}" stroke-linejoin="round" transform="translate(0,4)"/>'
            f'<path d="{d}" fill="none" stroke="{ink}" stroke-width="{sw}" stroke-linejoin="round"/><path d="{d}" fill="{fill}"/>'
            f'<path d="{d}" fill="none" stroke="#ffffff" stroke-width="1" opacity=".45" transform="translate(0,-1)"/>')

GOLD = ('<linearGradient id="{id}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fff1b8"/><stop offset=".42" stop-color="#f0c45a"/>'
        '<stop offset=".5" stop-color="#9a6420"/><stop offset=".62" stop-color="#d9a744"/><stop offset="1" stop-color="#7a4c16"/></linearGradient>')
def metal(id, c):
    return (f'<linearGradient id="{id}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{c[0]}"/><stop offset=".42" stop-color="{c[1]}"/>'
            f'<stop offset=".5" stop-color="{c[2]}"/><stop offset=".64" stop-color="{c[3]}"/><stop offset="1" stop-color="{c[4]}"/></linearGradient>')

def plate(W, gold_id, fill, ink='#140f09'):
    """the game's name on its plate, centred at the top (y 16-72)"""
    r1, r1w = word('REALM', 40, 0, 0, 0.08); of_, ofw = word('OF', 22, 0, 0, 0.06); r2, r2w = word('LONER', 40, 0, 0, 0.08)
    gap = 10; tot = r1w + gap + ofw + gap + r2w; nx = (W - tot) / 2; a, b = nx - 34, nx + tot + 34
    r1, _ = word('REALM', 40, nx, 56, 0.08); of_, _ = word('OF', 22, nx + r1w + gap, 56, 0.06); r2, _ = word('LONER', 40, nx + r1w + gap + ofw + gap, 56, 0.08)
    p = f'M{a},16 L{b},16 L{b + 16},44 L{b},72 L{a},72 L{a - 16},44 Z'
    return (f'<path d="{p}" fill="{fill}" stroke="{ink}" stroke-width="6" stroke-linejoin="round"/><path d="{p}" fill="none" stroke="#d9a744" stroke-width="2.4" stroke-linejoin="round"/>'
            + letters(r1, 5, f'url(#{gold_id})', ink) + letters(of_, 4, f'url(#{gold_id})', ink) + letters(r2, 5, f'url(#{gold_id})', ink))

def write(svg, svg_path, js_name, art_key, made_by):
    """the SVG next to its script, and the game's one-line copy in src/<js_name>"""
    open(svg_path, 'w').write(svg)
    flat = re.sub(r'<!--.*?-->', '', svg, flags=re.S); flat = re.sub(r'>\s+<', '><', flat).strip()
    open(os.path.join(ROOT, 'src', js_name), 'w').write(f'// Generated by {made_by}; do not edit by hand.\n(function (root) {{ root.ART = root.ART || {{}}; root.ART.{art_key} = '
        + json.dumps(flat) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
    return len(flat)

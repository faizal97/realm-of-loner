# The three chapter logos of The Ruinfall Saga, each its own composition and lettering idea (no shared template):
#   1  THE ASHEN CORONATION: ASHEN bent into a crown band with a gold crown standing on it, its lower edge crumbling to ash
#   2  THE FIRST WOUND: WOUND in storm-steel, torn along a diagonal rift of white-blue light that drips
#   3  RUINFALL: RUIN solid, FALL tumbling apart with molten cracks, a black dragon's wings behind
# Each keeps the saga emblem (ART.emblem, small) and "THE RUINFALL SAGA · CHAPTER N". Ids are prefixed c1_/c2_/c3_.
# Usage: python3 art/ruinfall/chapters.py  ->  art/ruinfall/chapter1.svg, chapter2.svg, chapter3.svg (not in the game yet)
import json, math, os, random, re, sys
H = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(H, '..', '..')
sys.path.insert(0, os.path.join(H, '..', 'brand'))
from lockup import word, centred, _cm, _gs, _hm, _upm  # the game's face (Marcellus SC) as outlines (art/brand/lockup.py)
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

W, Hh = 640, 330
CAP = 0.70  # Marcellus caps stand about 0.7 em
INK = '#0c0806'
f1 = lambda v: f'{v:.1f}'


def adv(ch, size):
    return size * 0.32 if ch == ' ' else _hm[_cm[ord(ch)]][0] * size / _upm


def glyph(ch, size, cx, by, deg=0.0):
    """one letter as an outline, its baseline centred on (cx, by), turned deg clockwise about that point"""
    k = size / _upm; w = adv(ch, size); a = math.radians(deg); c, s = math.cos(a), math.sin(a)
    pen = SVGPathPen(_gs)
    _gs[_cm[ord(ch)]].draw(TransformPen(pen, (k * c, k * s, k * s, -k * c, cx - w / 2 * c, by - w / 2 * s)))
    return re.sub(r'(\d+\.\d)\d+', r'\1', pen.getCommands())


def carve(paths, sw, fills, hi='#ffffff', hi_o=.45, ink=INK, drop=4):
    """carved letters, all drops first, then all outlines, the fills and the thin top light (so letters never cover each other's fill)"""
    if isinstance(fills, str): fills = [fills] * len(paths)
    o = ''.join(f'<path d="{d}" fill="{ink}" stroke="{ink}" stroke-width="{sw}" stroke-linejoin="round" transform="translate(0,{drop})"/>' for d in paths)
    o += ''.join(f'<path d="{d}" fill="none" stroke="{ink}" stroke-width="{sw}" stroke-linejoin="round"/>' for d in paths)
    o += ''.join(f'<path d="{d}" fill="{f}"/>' for d, f in zip(paths, fills))
    o += ''.join(f'<path d="{d}" fill="none" stroke="{hi}" stroke-width="1" opacity="{hi_o}" transform="translate(0,-1)"/>' for d in paths)
    return o


def ramp(id, stops, p1=None, p2=None):
    """a vertical metal ramp; with p1 (cap top) and p2 (baseline) it follows a turned letter"""
    st = ''.join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in stops)
    if p1 is None: return f'<linearGradient id="{id}" x1="0" y1="0" x2="0" y2="1">{st}</linearGradient>'
    return (f'<linearGradient id="{id}" gradientUnits="userSpaceOnUse" x1="{f1(p1[0])}" y1="{f1(p1[1])}" x2="{f1(p2[0])}" y2="{f1(p2[1])}">{st}</linearGradient>')


def up_pts(cx, by, deg, size):
    a = math.radians(deg); h = size * CAP
    return (cx + h * math.sin(a), by - h * math.cos(a)), (cx, by)


GOLD = [(0, '#fff1b8'), (.42, '#f0c45a'), (.5, '#9a6420'), (.62, '#d9a744'), (1, '#7a4c16')]
BLUR = lambda id, sd: f'<filter id="{id}" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="{sd}"/></filter>'

_em = json.loads(re.search(r'ART\.emblem = (".*?");', open(os.path.join(ROOT, 'src', 'art_ruinfall.js')).read()).group(1))
_em = re.sub(r'^<svg[^>]*>|</svg>$', '', _em)


def emblem(P, cx, cy, size):
    """the saga emblem (256 box, coin centre 128,118), centred on cx,cy at size px across the coin"""
    k = size / 200
    inner = re.sub(r'\b(id="|url\(#|href="#)rf', r'\1' + P + 'em', _em)
    return f'<g transform="translate({f1(cx - 128 * k)},{f1(cy - 118 * k)}) scale({k:.3f})">{inner}</g>'


def sub_line(P, n, base, fill, size=13, x=None):
    t = f'THE RUINFALL SAGA  ·  CHAPTER {["ONE", "TWO", "THREE"][n - 1]}'
    if x is None: d, w = centred(t, size, base, 0.24, W)
    else: d, w = word(t, size, x, base, 0.24)
    return carve([d], 3.5, fill, drop=2), w


def svg(n, defs, body, note):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{Hh}" viewBox="0 0 {W} {Hh}">\n'
            f'  <!-- The Ruinfall Saga, chapter {n} logo: {note} Generated by art/ruinfall/chapters.py -->\n'
            f'  <defs>{defs}</defs>\n{body}\n</svg>\n')


# ---------------------------------------------------------------- Chapter One: THE ASHEN CORONATION
def chapter1():
    P = 'c1_'; rnd = random.Random(11)
    size, R, top_base = 116, 400, 206; cx0, cy0 = W / 2, top_base + R  # ASHEN on an upward arc (centre below)
    tr = 0.02 * size
    ws = [adv(c, size) for c in 'ASHEN']; tot = sum(ws) + tr * 4
    paths, grads, fills, s = [], '', [], -tot / 2
    for i, (ch, w) in enumerate(zip('ASHEN', ws)):
        th = (s + w / 2) / R; s += w + tr
        x, y = cx0 + R * math.sin(th), cy0 - R * math.cos(th); deg = math.degrees(th)
        paths.append(glyph(ch, size, x, y, deg))
        p1, p2 = up_pts(x, y, deg, size)
        grads += ramp(f'{P}ash{i}', [(0, '#ffffff'), (.4, '#d6d1c9'), (.5, '#4a443e'), (.62, '#a49d93'), (1, '#4c4640')], p1, p2)
        fills.append(f'url(#{P}ash{i})')
    span = tot / 2 / R + .04
    # the crumbled lower edge: everything inside radius R + d(theta) is gone; d is ragged, deeper in places
    pts, th = [], -span
    while th <= span:
        d = rnd.choice([7, 9, 11]) if rnd.random() < .22 else rnd.uniform(1.5, 5)  # mostly shallow, a few bites (the E keeps its foot)
        pts.append((th, d)); th += math.radians(rnd.uniform(.5, 1.3))
    edge = [(cx0 + (R + d) * math.sin(t), cy0 - (R + d) * math.cos(t)) for t, d in pts]
    cut = 'M' + ' L'.join(f'{f1(x)},{f1(y)}' for x, y in edge) + f' L{f1(cx0)},{f1(cy0)} Z'
    edge_line = ' '.join(f'{f1(x)},{f1(y)}' for x, y in edge)
    # flakes breaking off just under the edge (letter-coloured), then ash and embers falling
    pits = ''
    for _ in range(24):  # pitting just above the ragged edge, the metal going to ash from below
        t = rnd.uniform(-span, span); r = R + rnd.uniform(12, 26); x, y = cx0 + r * math.sin(t), cy0 - r * math.cos(t); k = rnd.uniform(.8, 2)
        pits += f'<polygon points="{f1(x - k)},{f1(y)} {f1(x + k * .4)},{f1(y - k)} {f1(x + k)},{f1(y + k * .7)}" fill="#000"/>'
    centres = [(cx0 + R * math.sin(t), cy0 - R * math.cos(t), w) for t, w in zip([(sum(ws[:i]) + tr * i + ws[i] / 2 - tot / 2) / R for i in range(5)], ws)]
    chips, ash = '', ''
    for _ in range(46):  # flakes of the letters breaking off, biggest nearest the edge
        lx, ly, lw = rnd.choice(centres); fall = rnd.uniform(0, 1) ** 1.6 * 40
        x, y = lx + rnd.uniform(-.42, .42) * lw + fall * .15, ly + 6 + fall
        k = rnd.uniform(2.2, 5.5) * (1 - fall / 70); a = rnd.uniform(0, 6.28)
        poly = ' '.join(f'{f1(x + k * math.cos(a + j * 2.1 + rnd.uniform(-.4, .4)))},{f1(y + k * math.sin(a + j * 2.1))}' for j in range(3))
        chips += f'<polygon points="{poly}" fill="{rnd.choice(["#bdb6ab", "#8f877c", "#d9d3c9", "#6f6860"])}" stroke="{INK}" stroke-width="1"/>'
    for _ in range(110):
        lx, ly, lw = rnd.choice(centres); fall = rnd.uniform(4, 70) ** 1.1
        x, y = lx + rnd.uniform(-.5, .5) * lw + fall * .18, ly + fall
        if y > 300: continue
        ember = rnd.random() < .28; r = rnd.uniform(.6, 1.7) * (1.15 - fall / 140)
        col = rnd.choice(['#ff8a2a', '#ffb45a']) if ember else rnd.choice(['#9a938a', '#c9c3ba', '#6f6860'])
        ash += f'<circle cx="{f1(x)}" cy="{f1(y)}" r="{r:.2f}" fill="{col}" opacity="{(1 - fall / 150) * (.95 if ember else .8):.2f}"/>'
    # the crown, standing on the top of the arch (the H's cap line), five tall points with finials, gems on the band
    cb = top_base - size * CAP - 1  # cap line of the middle letter
    pts_x = [-78, -40, 0, 40, 78]; tips = [-58, -84, -104, -84, -58]
    crown = f'M{-82},{-14}'
    for i, (px, tp) in enumerate(zip(pts_x, tips)):
        crown += f' L{px - (6 if i else 0)},{tp + 18} L{px},{tp} L{px + (6 if i < 4 else 0)},{tp + 18}'
        if i < 4: vx = (px + pts_x[i + 1]) / 2; crown += f' Q{vx},{-26 - (6 if i in (1, 2) else 0)} {pts_x[i + 1] - 6},{tips[i + 1] + 18}'
    crown += ' L82,-14 Z'
    band = 'M-90,-18 Q0,-26 90,-18 L92,2 Q0,-6 -92,2 Z'
    finial = ''.join(f'<circle cx="{px}" cy="{tp - 4}" r="{6 if i == 2 else 4.6}" fill="url(#{P}gold)" stroke="{INK}" stroke-width="2.6"/>' for i, (px, tp) in enumerate(zip(pts_x, tips)))
    gems = ''.join(f'<path d="M{gx},{-15} l5,6 l-5,6 l-5,-6 Z" fill="{gc}" stroke="{INK}" stroke-width="1.8"/>' for gx, gc in [(-62, '#ff5a2a'), (-31, '#e8e2d6'), (31, '#e8e2d6'), (62, '#ff5a2a')])
    crown_g = (f'<g transform="translate({cx0},{f1(cb)})">'
               f'<ellipse cx="0" cy="-50" rx="110" ry="50" fill="#ffb84a" opacity=".22" filter="url(#{P}blur)"/>'
               f'<path d="{crown}" fill="{INK}" stroke="{INK}" stroke-width="8" stroke-linejoin="round" transform="translate(0,3)"/>'
               f'<path d="{crown}" fill="url(#{P}crown)" stroke="{INK}" stroke-width="4.5" stroke-linejoin="round"/>'
               f'<path d="{crown}" fill="none" stroke="#fff3c0" stroke-width="1.2" opacity=".6" transform="translate(0,-1.2)"/>'
               + ''.join(f'<path d="M{px},{tp + 6} L{px},{-30}" stroke="#7a4c16" stroke-width="1.6" opacity=".7"/>' for px, tp in zip(pts_x, tips))
               + f'{finial}<path d="{band}" fill="url(#{P}gold)" stroke="{INK}" stroke-width="4" stroke-linejoin="round"/>{gems}'
               + emblem(P, 0, -44, 46) + '</g>')
    # THE: small, riding the arc above the A and S
    the_p, s = [], -tot / 2 + 6
    for ch in 'THE':
        w = adv(ch, 22); th = (s + w / 2) / (R + size * CAP + 16); s += w + 0.3 * 22
        rr = R + size * CAP + 14; x, y = cx0 + rr * math.sin(th), cy0 - rr * math.cos(th)
        the_p.append(glyph(ch, 22, x, y, math.degrees(th)))
    cor, cw = centred('CORONATION', 56, 286, 0.09, W)
    sub, _ = sub_line(P, 1, 318, f'url(#{P}silver)')
    ruleL = f'M{f1(W / 2 - cw / 2 - 4)},270 L{f1(W / 2 - cw / 2 - 40)},270'; ruleR = f'M{f1(W / 2 + cw / 2 + 4)},270 L{f1(W / 2 + cw / 2 + 40)},270'
    defs = (ramp(f'{P}gold', GOLD) + ramp(f'{P}crown', [(0, '#fff6cf'), (.45, '#f2c75c'), (.72, '#b07a28'), (1, '#7a4c16')]) + grads
            + ramp(f'{P}silver', [(0, '#ffffff'), (.45, '#cfc9bf'), (.55, '#6c655d'), (1, '#a49d93')])
            + BLUR(f'{P}blur', 14) + BLUR(f'{P}soft', 1.6) + BLUR(f'{P}glow', 4)
            + f'<mask id="{P}crumble" maskUnits="userSpaceOnUse" x="0" y="0" width="{W}" height="{Hh}"><rect width="{W}" height="{Hh}" fill="#fff"/><path d="{cut}" fill="#000"/>{pits}</mask>'
            + f'<clipPath id="{P}letters"><path d="{" ".join(paths)}"/></clipPath>')
    body = (f'  {ash}\n  {crown_g}\n'
            f'  <g mask="url(#{P}crumble)">{carve(paths, 9, fills, hi_o=.6)}'
            f'<g clip-path="url(#{P}letters)"><polyline points="{edge_line}" fill="none" stroke="#ff6a12" stroke-width="12" opacity=".85" filter="url(#{P}glow)"/>'
            f'<polyline points="{edge_line}" fill="none" stroke="#ffc070" stroke-width="3"/></g></g>\n'
            f'  {chips}\n  {carve(the_p, 5, f"url(#{P}silver)", drop=3)}\n'
            f'  {carve([cor], 7, f"url(#{P}gold)", hi="#fff3c0", hi_o=.55)}\n'
            f'  <path d="{ruleL} {ruleR}" stroke="{INK}" stroke-width="5"/><path d="{ruleL} {ruleR}" stroke="#d9a744" stroke-width="1.8"/>\n  {sub}')
    return svg(1, defs, body, 'ASHEN bent into a crown band, a gold crown on it, its lower edge crumbling to ash.')


# ---------------------------------------------------------------- Chapter Two: THE FIRST WOUND
def chapter2():
    P = 'c2_'; rnd = random.Random(22)
    size, base = 150, 274
    wd, ww = centred('WOUND', size, base, 0.0, W); x0 = (W - ww) / 2
    # the rift: a jagged diagonal from lower left to upper right through the middle of the word
    a, b = (x0 - 16, 242), (x0 + ww + 16, 200)
    tear = [a]
    for i in range(1, 13):
        t = i / 13; x = a[0] + (b[0] - a[0]) * t; y = a[1] + (b[1] - a[1]) * t
        tear.append((x + rnd.uniform(-10, 10), y + (1 if i % 2 else -1) * rnd.uniform(2, 13)))  # a zigzag, uneven teeth
    tear.append(b)
    ts = ' '.join(f'{f1(x)},{f1(y)}' for x, y in tear)
    top = f'M{ts} L{W},{b[1]} L{W},0 L0,0 L0,{a[1]} Z'; bot = f'M{ts} L{W},{b[1]} L{W},{Hh} L0,{Hh} L0,{a[1]} Z'
    word_g = carve([wd], 10, f'url(#{P}steel)', hi='#eaf6ff', hi_o=.7)
    # the light in the tear: a lens, widest in the middle, tapering to nothing at both ends
    def lens(half):
        up, dn = [], []
        for i, (x, y) in enumerate(tear):
            t = i / (len(tear) - 1); h = half * math.sin(math.pi * t) ** .7
            up.append((x + 1.5 * h, y - h)); dn.append((x - 1.5 * h, y + h))
        return 'M' + ' L'.join(f'{f1(x)},{f1(y)}' for x, y in up + dn[::-1]) + ' Z'
    # drips of light running from the tear's lower lip and falling free below the word
    drips = ''
    for i, ln in [(2, 40), (5, 50), (8, 34), (11, 54)]:
        x, y = tear[i]; y += 4; x2 = x - 3
        drips += (f'<path d="M{f1(x - 1.6)},{f1(y)} Q{f1(x2)},{f1(y + ln * .6)} {f1(x2 - .5)},{f1(y + ln)} L{f1(x2 + .5)},{f1(y + ln)} Q{f1(x2 + 1)},{f1(y + ln * .6)} {f1(x + 1.6)},{f1(y)} Z" fill="#cfeaff"/>'
                  f'<path d="M{f1(x2)},{f1(y + ln + 8)} q-4,6 0,10 q4,-4 0,-10 Z" fill="#ffffff"/>')
        drips += f'<circle cx="{f1(x2)}" cy="{f1(y + ln + 23)}" r="1.4" fill="#cfeaff" opacity=".8"/>'
    spray = ''
    for _ in range(60):  # sea-spray thrown up and out of the tear, thicker near its two ends and above it
        e = rnd.choice([a, b]); sgn = 1 if e is b else -1; r = rnd.uniform(4, 110) ** 1.0; ang = rnd.uniform(-1.4, .5)
        x = e[0] - sgn * 30 + sgn * r * math.cos(ang); y = e[1] + r * math.sin(ang) * .8
        if not (4 < x < W - 4 and 90 < y < 300): continue
        spray += f'<circle cx="{f1(x)}" cy="{f1(y)}" r="{rnd.uniform(.5, 1.8):.2f}" fill="{rnd.choice(["#ffffff", "#cfe6ff", "#9ad4ff"])}" opacity="{rnd.uniform(.35, .9):.2f}"/>'
    # THE · emblem · FIRST, small and spaced
    ts_, tw = word('THE', 36, 0, 0, .42); fs, fw = word('FIRST', 36, 0, 0, .42); gap = 70
    tx = (W - (tw + gap + fw)) / 2; ts_, _ = word('THE', 36, tx, 112, .42); fs, _ = word('FIRST', 36, tx + tw + gap, 112, .42)
    sub, _ = sub_line(P, 2, 320, f'url(#{P}frost)')
    steel = [(0, '#ffffff'), (.36, '#c4d6ea'), (.5, '#26364e'), (.6, '#7d98ba'), (1, '#1a273c')]
    defs = (ramp(f'{P}steel', steel) + ramp(f'{P}frost', [(0, '#ffffff'), (.45, '#cfe2f6'), (.55, '#5d7898'), (1, '#9fb8d6')])
            + BLUR(f'{P}blur', 12) + BLUR(f'{P}glow', 4) + BLUR(f'{P}soft', 1.4)
            + f'<clipPath id="{P}top"><path d="{top}"/></clipPath><clipPath id="{P}bot"><path d="{bot}"/></clipPath>')
    body = (f'  {spray}\n'
            f'  <path d="{lens(16)}" fill="#3a8cff" opacity=".9" filter="url(#{P}blur)"/>\n'
            f'  <g transform="translate(-6,5)"><g clip-path="url(#{P}bot)">{word_g}</g></g>\n'
            f'  <g transform="translate(12,-9)"><g clip-path="url(#{P}top)">{word_g}</g></g>\n'
            f'  <path d="{lens(9)}" fill="#7cc4ff" filter="url(#{P}glow)"/><path d="{lens(5)}" fill="#d8f0ff" filter="url(#{P}soft)"/><path d="{lens(2.2)}" fill="#ffffff"/>\n'
            f'  <g filter="url(#{P}glow)" opacity=".9">{drips}</g>{drips}\n'
            f'  {carve([ts_, fs], 5, f"url(#{P}frost)", drop=3, hi_o=.6)}{emblem(P, tx + tw + gap / 2, 99, 48)}\n  {sub}')
    return svg(2, defs, body, 'WOUND in storm-steel, torn along a diagonal rift of white-blue light that drips.')


# ---------------------------------------------------------------- Chapter Three: RUINFALL
def chapter3():
    P = 'c3_'; rnd = random.Random(33)
    obs = [(0, '#9b908a'), (.28, '#3a3230'), (.5, '#0e0a09'), (.66, '#2a1208'), (.86, '#b8420c'), (1, '#ff9a3a')]
    # the wings: a black dragon's pair spread behind the word, ribbed, edged with ember light
    def wing(sx):
        sh = (0, 0); wr = (150, -128)  # shoulder at the root, the wrist up and out
        tips = [(296, -112), (300, -36), (262, 40), (196, 78), (110, 86)]
        d = f'M{sh[0]},{sh[1]} Q60,-110 {wr[0]},{wr[1]} L{tips[0][0]},{tips[0][1]}'
        prev = tips[0]
        for tp in tips[1:]:
            mx, my = (prev[0] + tp[0]) / 2, (prev[1] + tp[1]) / 2; ix, iy = mx - (mx - wr[0]) * .26, my - (my - wr[1]) * .26
            d += f' Q{f1(ix)},{f1(iy)} {tp[0]},{tp[1]}'; prev = tp
        d += f' Q70,60 {sh[0] + 20},{sh[1] + 40} Z'
        ribs = ''.join(f'M{wr[0]},{wr[1]} Q{f1((wr[0] + tx) / 2 + 8)},{f1((wr[1] + ty) / 2 - 6)} {tx},{ty} ' for tx, ty in tips)
        g = (f'<path d="{d}" fill="none" stroke="#ff6a12" stroke-width="10" opacity=".55" filter="url(#{P}glow)"/>'
             f'<path d="{d}" fill="url(#{P}wing)" stroke="#120806" stroke-width="5" stroke-linejoin="round"/>'
             f'<path d="{d}" fill="none" stroke="#ff8a2a" stroke-width="1.6" stroke-linejoin="round" opacity=".9"/>'
             f'<path d="{ribs}" fill="none" stroke="#120806" stroke-width="6" stroke-linecap="round"/>'
             f'<path d="{ribs}" fill="none" stroke="#7a2a0a" stroke-width="2" stroke-linecap="round"/>'
             f'<path d="M{sh[0]},{sh[1]} Q60,-110 {wr[0]},{wr[1]}" fill="none" stroke="#120806" stroke-width="9" stroke-linecap="round"/>'
             f'<path d="M{sh[0]},{sh[1]} Q60,-110 {wr[0]},{wr[1]}" fill="none" stroke="#b24a12" stroke-width="2.4" stroke-linecap="round"/>'
             f'<path d="M{wr[0]},{wr[1]} l-4,-16 l10,12 Z" fill="#1a0c08" stroke="#ff8a2a" stroke-width="1.2"/>')
        return f'<g transform="translate({W / 2 + sx * 26},156) scale({sx * .9},.9)">{g}</g>'
    # RUIN: one heavy solid line
    rsize, rbase = 128, 150
    rd, rw = centred('RUIN', rsize, rbase, 0.03, W); rx = (W - rw) / 2
    # FALL: each letter turned and dropped more than the last, as if breaking loose
    fsize, fbase = 106, 248
    turn = [(0, 0, -2), (6, 6, 7), (18, 18, 19), (38, 34, 38)]  # (drop px, extra gap px, degrees)
    ws = [adv(c, fsize) for c in 'FALL']; tot = sum(ws) + 54; x = (W - tot) / 2 - 18
    fp, grads, fills, cracks_clip, places = [], ramp(f'{P}ruin', obs), [], [], []
    for i, (ch, w) in enumerate(zip('FALL', ws)):
        dy, gx, deg = turn[i]; x += gx; cx = x + w / 2; by = fbase + dy
        fp.append(glyph(ch, fsize, cx, by, deg)); p1, p2 = up_pts(cx, by, deg, fsize)
        grads += ramp(f'{P}f{i}', obs, p1, p2); fills.append(f'url(#{P}f{i})'); places.append((cx, by, deg)); x += w + 2
    # molten cracks inside the letters (clipped to them), more of them the further a letter has fallen
    cracks = ''
    for i, (cx, by, deg) in enumerate(places):
        for _ in range(1 + i):
            px, py = cx + rnd.uniform(-22, 22), by - rnd.uniform(10, 66); pts = [(px, py)]
            for _ in range(rnd.randint(3, 5)):
                px += rnd.uniform(-12, 12); py += rnd.uniform(6, 16); pts.append((px, py))
            cracks += ' '.join(f'{"M" if j == 0 else "L"}{f1(qx)},{f1(qy)}' for j, (qx, qy) in enumerate(pts)) + ' '
    for _ in range(3):  # and a couple running down through RUIN
        px, py = rx + rnd.uniform(20, rw - 20), rbase - rsize * CAP + rnd.uniform(4, 20); pts = [(px, py)]
        for _ in range(4): px += rnd.uniform(-10, 10); py += rnd.uniform(10, 22); pts.append((px, py))
        cracks += ' '.join(f'{"M" if j == 0 else "L"}{f1(qx)},{f1(qy)}' for j, (qx, qy) in enumerate(pts)) + ' '
    chips = ''
    for _ in range(22):  # stone chips falling from the broken letters, more toward the right
        t = rnd.random() ** .6; cx = W / 2 - 90 + t * 260 + rnd.uniform(-20, 20); cy = min(fbase - 30 + t * 50 + rnd.uniform(-10, 60), 296)  # clear of the line below
        k = rnd.uniform(2, 5.5); a = rnd.uniform(0, 6.28)
        poly = ' '.join(f'{f1(cx + k * math.cos(a + j * 1.7 + rnd.uniform(-.3, .3)) * rnd.uniform(.7, 1.2))},{f1(cy + k * math.sin(a + j * 1.7))}' for j in range(4))
        chips += f'<polygon points="{poly}" fill="#1a1210" stroke="#ff7a1a" stroke-width=".9" stroke-linejoin="round"/>'
    embers = ''.join(f'<circle cx="{f1(rnd.uniform(20, W - 20))}" cy="{f1(rnd.uniform(20, 300))}" r="{rnd.uniform(.6, 1.8):.2f}" fill="{rnd.choice(["#ff9a4a", "#ffcf7a", "#ff6a1a"])}" opacity="{rnd.uniform(.4, .9):.2f}"/>' for _ in range(30))
    sub, sw = sub_line(P, 3, 318, f'url(#{P}bronze)', size=13)
    defs = (grads + ramp(f'{P}bronze', [(0, '#ffe6b0'), (.45, '#e09a4a'), (.55, '#6a2a0a'), (1, '#c06a24')])
            + ramp(f'{P}wing', [(0, '#2a1a14'), (.6, '#0e0806'), (1, '#1e0c06')])
            + BLUR(f'{P}glow', 5) + BLUR(f'{P}blur', 12) + BLUR(f'{P}soft', 1.2)
            + f'<clipPath id="{P}let"><path d="{rd} {" ".join(fp)}"/></clipPath>')
    hot = lambda ps: ''.join(f'<path d="{d}" fill="none" stroke="#ff6a12" stroke-width="12" opacity=".5" filter="url(#{P}blur)"/>' for d in ps)
    body = (f'  {embers}\n  {wing(1)}{wing(-1)}\n'
            f'  {emblem(P, W / 2, 34, 44)}\n'
            f'  {hot([rd] + fp)}\n'
            f'  {carve([rd], 10, f"url(#{P}ruin)", hi="#ffffff", hi_o=.5, ink="#050302")}\n'
            f'  {carve(fp, 9, fills, hi="#ffffff", hi_o=.5, ink="#050302")}\n'
            f'  <g clip-path="url(#{P}let)"><path d="{cracks}" fill="none" stroke="#ff5a0a" stroke-width="6" filter="url(#{P}glow)"/>'
            f'<path d="{cracks}" fill="none" stroke="#ff9a3a" stroke-width="2.4" stroke-linejoin="round"/><path d="{cracks}" fill="none" stroke="#fff0b0" stroke-width=".9" stroke-linejoin="round"/></g>\n'
            f'  {chips}\n  {sub}')
    return svg(3, defs, body, 'RUIN solid, FALL tumbling apart with molten cracks, a black dragon\'s wings behind.')



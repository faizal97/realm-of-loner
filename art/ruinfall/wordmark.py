# The game's name with "The Ruinfall Saga" under it: one logo (#524): Marcellus SC (the game's own display face) as outlines, carved gold, split by the
# emblem's burning crack, the emblem above. Writes wordmark.svg and src/art_ruinfall_word.js (ART.ruinfallWord).
# Needs fontTools + brotli and the font from fonts/fonts.local.css.
import base64, json, os, re, sys
H = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(H, '..', '..')
sys.path.insert(0, os.path.join(H, '..', 'brand')); from lockup import word, centred  # the game's face as outlines (art/brand/lockup.py)

W, Hh = 640, 300
big, bw = word('RUINFALL', 118, 0, 0, 0.04)
bx = (W - bw) / 2
big, _ = word('RUINFALL', 118, bx, 230, 0.04)
the, tw = word('THE', 24, 0, 0, 0.3); the, _ = word('THE', 24, bx + 8, 136, 0.3)
saga, sw = word('SAGA', 34, 0, 0, 0.42); sx = (W - sw) / 2; saga, _ = word('SAGA', 34, sx, 284, 0.42)
# the game's own name above, as on the title screen: Realm, a small "of", Loner
r1, r1w = word('REALM', 40, 0, 0, 0.08); of_, ofw = word('OF', 22, 0, 0, 0.06); r2, r2w = word('LONER', 40, 0, 0, 0.08)
gap = 10; tot = r1w + gap + ofw + gap + r2w; nx = (W - tot) / 2
r1, _ = word('REALM', 40, nx, 56, 0.08); of_, _ = word('OF', 22, nx + r1w + gap, 56, 0.06); r2, _ = word('LONER', 40, nx + r1w + gap + ofw + gap, 56, 0.08)
px0, px1 = nx - 34, nx + tot + 34
# the crack runs down through the word between the N and the F, off-true like the emblem's
crack = [(301, 143), (291, 166), (306, 180), (281, 202), (294, 215), (275, 238)]  # starts where the coin's crack ends
cs = ' '.join(f'{x},{y}' for x, y in crack)
L = f'M{cs} L275,{Hh} L0,{Hh} L0,0 L301,0 Z'; R = f'M{cs} L275,{Hh} L{W},{Hh} L{W},0 L301,0 Z'
rule = lambda x1, x2: f'<path d="M{x1},268 L{x2},268" stroke="#140f09" stroke-width="5"/><path d="M{x1},268 L{x2},268" stroke="#d9a744" stroke-width="2"/>'
dia = lambda x: f'<path d="M{x},261 L{x + 7},268 L{x},275 L{x - 7},268 Z" fill="url(#wmGold)" stroke="#140f09" stroke-width="2"/>'
letters = lambda d, sw_: f'<path d="{d}" fill="#140f09" stroke="#140f09" stroke-width="{sw_}" stroke-linejoin="round" transform="translate(0,4)"/><path d="{d}" fill="none" stroke="#140f09" stroke-width="{sw_}" stroke-linejoin="round"/><path d="{d}" fill="url(#wmGold)"/><path d="{d}" fill="none" stroke="#fff3c0" stroke-width="1" opacity=".55" transform="translate(0,-1)"/>'
word_g = letters(big, 9)
em = json.loads(re.search(r'ART\.emblem = (".*?");', open(os.path.join(ROOT, 'src', 'art_ruinfall.js')).read()).group(1))
em_inner = re.sub(r'^<svg[^>]*>|</svg>$', '', em)
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{Hh}" viewBox="0 0 {W} {Hh}">
  <!-- The Ruinfall Saga wordmark (#524). Generated by art/ruinfall/wordmark.py -->
  <defs>
    <linearGradient id="wmGold" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fff1b8"/><stop offset=".42" stop-color="#f0c45a"/><stop offset=".5" stop-color="#9a6420"/><stop offset=".62" stop-color="#d9a744"/><stop offset="1" stop-color="#7a4c16"/></linearGradient>
    <filter id="wmBlur" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="8"/></filter>
    <filter id="wmSoft" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="1.4"/></filter>
    <clipPath id="wmL"><path d="{L}"/></clipPath><clipPath id="wmR"><path d="{R}"/></clipPath>
  </defs>
  <path d="M{px0},16 L{px1},16 L{px1 + 16},44 L{px1},72 L{px0},72 L{px0 - 16},44 Z" fill="#241a10" stroke="#140f09" stroke-width="6" stroke-linejoin="round"/>
  <path d="M{px0},16 L{px1},16 L{px1 + 16},44 L{px1},72 L{px0},72 L{px0 - 16},44 Z" fill="none" stroke="#d9a744" stroke-width="2.4" stroke-linejoin="round"/>
  <path d="M{px0 + 4},21 L{px1 - 4},21 L{px1 + 9},44 L{px1 - 4},67 L{px0 + 4},67 L{px0 - 9},44 Z" fill="none" stroke="#7a4c16" stroke-width="1.2" stroke-linejoin="round"/>
  {letters(r1, 5)}{letters(of_, 4)}{letters(r2, 5)}
  <g transform="translate({W / 2 - 128 * .4},{108 - 118 * .4}) scale(.4)">{em_inner}</g>
  <polyline points="{cs}" fill="none" stroke="#ff7a1a" stroke-width="20" stroke-linejoin="round" filter="url(#wmBlur)"/>
  <g transform="translate(-4,-1.5)"><g clip-path="url(#wmL)">{word_g}</g></g>
  <g transform="translate(4,1.5)"><g clip-path="url(#wmR)">{word_g}</g></g>
  <polyline points="{cs}" fill="none" stroke="#ff7a1a" stroke-width="6" stroke-linejoin="round" filter="url(#wmSoft)"/>
  <polyline points="{cs}" fill="none" stroke="#ffe3a0" stroke-width="2.2" stroke-linejoin="round" filter="url(#wmSoft)"/>
  {letters(the, 6)}
  {rule(sx - 150, sx - 26)}{dia(sx - 150)}{rule(sx + sw + 26, sx + sw + 150)}{dia(sx + sw + 150)}
  {letters(saga, 6)}
</svg>
'''
open(os.path.join(H, 'wordmark.svg'), 'w').write(svg)
flat = re.sub(r'<!--.*?-->', '', svg, flags=re.S); flat = re.sub(r'>\s+<', '><', flat).strip()
open(os.path.join(ROOT, 'src', 'art_ruinfall_word.js'), 'w').write('// "The Ruinfall Saga" wordmark (#524), generated by art/ruinfall/wordmark.py; do not edit by hand.\n(function (root) { root.ART = root.ART || {}; root.ART.ruinfallWord = ' + json.dumps(flat) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
print('wordmark.svg', len(flat))
